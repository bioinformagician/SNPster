-- ===================================
-- Trigger: create imputation job when a new user is created
-- ===================================

CREATE OR REPLACE FUNCTION snpster_users.create_imputation_job_for_new_file()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    new_imputation_id integer;
BEGIN
    INSERT INTO snpster_users.imputation_jobs (
        user_id,
        imputation_status
    )
    VALUES (
        NEW.user_id,
        'queued'
    )
    RETURNING imputation_id INTO new_imputation_id;

    INSERT INTO snpster_users.imputation_job_parameters (
        imputation_id,
        file_id
    )
    VALUES (
        new_imputation_id,
        NEW.file_id
    );

    INSERT INTO snpster_users.user_ancestry (
        user_id
    )
    VALUES (
        NEW.user_id
    )
    ON CONFLICT (user_id) DO NOTHING;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_create_imputation_job_on_user_insert
ON snpster_users.user_information;

DROP TRIGGER IF EXISTS trg_create_imputation_job_on_file_insert
ON snpster_users.user_files;

CREATE TRIGGER trg_create_imputation_job_on_file_insert
AFTER INSERT ON snpster_users.user_files
FOR EACH ROW
EXECUTE FUNCTION snpster_users.create_imputation_job_for_new_file();
-- ===================================
-- Trigger: set started_at / completed_at timestamps on status changes
-- ===================================

CREATE OR REPLACE FUNCTION snpster_users.set_imputation_job_timestamps()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.imputation_status = 'running' AND (OLD.imputation_status IS DISTINCT FROM 'running') THEN
        NEW.started_at := CURRENT_TIMESTAMP;
    END IF;
    IF NEW.imputation_status = 'completed' AND (OLD.imputation_status IS DISTINCT FROM 'completed') THEN
        NEW.completed_at := CURRENT_TIMESTAMP;
    END IF;
    RETURN NEW;
END;
$$;

