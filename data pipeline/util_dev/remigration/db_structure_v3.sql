CREATE OR REPLACE FUNCTION data_libraries.enforce_unspecified_diabetes_mapping()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.raw_outcome = 'TTE unspecified diabetes mellitus' THEN
        SELECT rt.report_trait_id
        INTO NEW.target_report_trait_id
        FROM data_libraries.report_traits AS rt
        JOIN data_libraries.report_categories AS rc
          ON rc.category_id = rt.category_id
        WHERE rt.display_name = 'Diabetes'
          AND rc.display_name = 'Metabolism & Hormones'
          AND rt.is_active
          AND rc.is_active;

        IF NEW.target_report_trait_id IS NULL THEN
            RAISE EXCEPTION
                'Could not find active report trait Diabetes in Metabolism & Hormones';
        END IF;

        NEW.cleaned_outcome := 'Diabetes';
        NEW.outcome_key := 'diabetes';
        NEW.mapping_status := 'mapped';
        NEW.curation_note :=
            'TTE unspecified diabetes mellitus is a diabetes evaluation endpoint; '
            'mapped to the consumer Diabetes card.';
        NEW.curation_version := '2026-09-14-v2';
        NEW.updated_at := CURRENT_TIMESTAMP;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_enforce_unspecified_diabetes_mapping
BEFORE INSERT OR UPDATE ON data_libraries.evaluation_outcome_mappings
FOR EACH ROW
EXECUTE FUNCTION data_libraries.enforce_unspecified_diabetes_mapping();

