BEGIN;

-- ================================================================
-- 1. Preserve additional dedicated-metric confidence intervals
-- ================================================================

ALTER TABLE data_libraries.pgs_performance
    ALTER COLUMN auroc TYPE NUMERIC(10,6) USING auroc::NUMERIC,
    ALTER COLUMN concordance_statistic TYPE NUMERIC(10,6) USING concordance_statistic::NUMERIC,
    ADD COLUMN IF NOT EXISTS beta_ci_lower NUMERIC,
    ADD COLUMN IF NOT EXISTS beta_ci_upper NUMERIC,
    ADD COLUMN IF NOT EXISTS auroc_ci_lower NUMERIC,
    ADD COLUMN IF NOT EXISTS auroc_ci_upper NUMERIC,
    ADD COLUMN IF NOT EXISTS concordance_statistic_ci_lower NUMERIC,
    ADD COLUMN IF NOT EXISTS concordance_statistic_ci_upper NUMERIC;

-- ================================================================
-- 2. Consumer-facing report taxonomy
-- ================================================================

CREATE TABLE IF NOT EXISTS data_libraries.report_categories (
    category_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_key VARCHAR(100) NOT NULL UNIQUE,
    display_name VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,
    display_order SMALLINT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_report_categories_order
    ON data_libraries.report_categories (display_order)
    WHERE is_active;


CREATE TABLE IF NOT EXISTS data_libraries.report_traits (
    report_trait_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trait_key VARCHAR(200) NOT NULL UNIQUE,
    display_name VARCHAR(255) NOT NULL,
    category_id SMALLINT NOT NULL
        REFERENCES data_libraries.report_categories(category_id)
        ON DELETE RESTRICT,
    description TEXT,
    display_order SMALLINT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (category_id, display_name)
);

CREATE INDEX IF NOT EXISTS idx_report_traits_category
    ON data_libraries.report_traits (category_id, display_order, display_name)
    WHERE is_active;


CREATE TABLE IF NOT EXISTS data_libraries.report_trait_scores (
    pgs_id VARCHAR(100) PRIMARY KEY
        REFERENCES data_libraries.pgscatalog_data(pgs_id)
        ON DELETE CASCADE,
    report_trait_id BIGINT NOT NULL
        REFERENCES data_libraries.report_traits(report_trait_id)
        ON DELETE RESTRICT,
    include_in_report BOOLEAN NOT NULL DEFAULT TRUE,
    curation_note TEXT,
    curation_version VARCHAR(50),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_report_trait_scores_trait
    ON data_libraries.report_trait_scores (report_trait_id)
    WHERE include_in_report;

-- ================================================================
-- 3. Evaluation-outcome curation
-- ================================================================

CREATE TABLE IF NOT EXISTS data_libraries.evaluation_outcome_mappings (
    raw_outcome TEXT PRIMARY KEY,
    cleaned_outcome VARCHAR(500) NOT NULL,
    outcome_key VARCHAR(250) NOT NULL,
    target_report_trait_id BIGINT
        REFERENCES data_libraries.report_traits(report_trait_id)
        ON DELETE SET NULL,
    mapping_status VARCHAR(20) NOT NULL DEFAULT 'mapped'
        CHECK (
            mapping_status IN (
                'mapped',
                'unmapped',
                'excluded',
                'needs_review'
            )
        ),
    curation_note TEXT,
    curation_version VARCHAR(50),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_evaluation_outcome_target
    ON data_libraries.evaluation_outcome_mappings (target_report_trait_id)
    WHERE target_report_trait_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_evaluation_outcome_key
    ON data_libraries.evaluation_outcome_mappings (outcome_key);

-- ================================================================
-- 4. Normalized performance metrics
-- ================================================================

CREATE TABLE IF NOT EXISTS data_libraries.performance_metric_types (
    metric_type VARCHAR(100) PRIMARY KEY,
    display_name VARCHAR(255) NOT NULL,
    metric_family VARCHAR(100) NOT NULL,
    default_display_mode VARCHAR(100),
    report_role TEXT,
    recommendation TEXT,
    display_order SMALLINT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS data_libraries.pgs_performance_metric_values (
    metric_value_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ppm_id VARCHAR(100) NOT NULL
        REFERENCES data_libraries.pgs_performance(ppm_id)
        ON DELETE CASCADE,
    metric_type VARCHAR(100) NOT NULL
        REFERENCES data_libraries.performance_metric_types(metric_type)
        ON DELETE RESTRICT,
    metric_index SMALLINT NOT NULL DEFAULT 1,
    source VARCHAR(30) NOT NULL
        CHECK (source IN ('dedicated', 'other_metric')),
    metric_label_raw TEXT,
    estimate NUMERIC,
    ci_lower NUMERIC,
    ci_upper NUMERIC,
    effect_basis VARCHAR(50)
        CHECK (
            effect_basis IS NULL
            OR effect_basis IN (
                'per_sd',
                'per_sd_assumed',
                'group_contrast',
                'absolute',
                'unknown',
                'not_applicable'
            )
        ),
    personalization_allowed BOOLEAN NOT NULL DEFAULT FALSE,
    display_mode VARCHAR(100),
    unit TEXT,
    contrast_text TEXT,
    raw_metric TEXT,
    parser_version VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (ppm_id, metric_type, source, metric_index)
);

CREATE INDEX IF NOT EXISTS idx_pgs_performance_metric_values_ppm
    ON data_libraries.pgs_performance_metric_values (ppm_id);

CREATE INDEX IF NOT EXISTS idx_pgs_performance_metric_values_type
    ON data_libraries.pgs_performance_metric_values (metric_type, ppm_id);

CREATE INDEX IF NOT EXISTS idx_pgs_performance_metric_values_personalizable
    ON data_libraries.pgs_performance_metric_values (ppm_id, metric_type)
    WHERE personalization_allowed;

-- ================================================================
-- 5. Views used by scoring/report code
-- ================================================================

CREATE OR REPLACE VIEW data_libraries.report_score_catalog_v AS
SELECT
    rts.pgs_id,
    rt.report_trait_id,
    rt.trait_key,
    rt.display_name AS reported_trait,
    rc.category_id,
    rc.category_key,
    rc.display_name AS category,
    rc.description AS category_description,
    rc.display_order AS category_display_order,
    rt.display_order AS trait_display_order,
    rts.include_in_report,
    rts.curation_version
FROM data_libraries.report_trait_scores AS rts
JOIN data_libraries.report_traits AS rt
    ON rt.report_trait_id = rts.report_trait_id
JOIN data_libraries.report_categories AS rc
    ON rc.category_id = rt.category_id
WHERE rts.include_in_report
  AND rt.is_active
  AND rc.is_active;


CREATE OR REPLACE VIEW data_libraries.pgs_performance_curated_v AS
SELECT
    pp.*,

    COALESCE(eom.cleaned_outcome, pp.reported_trait) AS evaluation_outcome_clean,
    eom.outcome_key AS evaluation_outcome_key,
    eom.mapping_status AS evaluation_mapping_status,
    target_trait.report_trait_id AS evaluation_target_report_trait_id,
    target_trait.display_name AS evaluation_target_trait,
    target_category.display_name AS evaluation_target_category,

    metrics.odds_ratio_estimate,
    metrics.odds_ratio_ci_lower,
    metrics.odds_ratio_ci_upper,
    metrics.odds_ratio_basis,
    metrics.odds_ratio_personalization_allowed,

    metrics.hazard_ratio_estimate,
    metrics.hazard_ratio_ci_lower,
    metrics.hazard_ratio_ci_upper,
    metrics.hazard_ratio_basis,
    metrics.hazard_ratio_personalization_allowed,

    metrics.beta_estimate,
    metrics.beta_ci_lower,
    metrics.beta_ci_upper,
    metrics.beta_basis,

    metrics.auroc_estimate,
    metrics.c_index_estimate,

    metrics.r2_value,
    metrics.incremental_r2_value,
    metrics.partial_r2_value,
    metrics.pseudo_r2_value,
    metrics.adjusted_r2_value,
    metrics.liability_r2_value,

    metrics.group_odds_ratio_raw,
    metrics.group_hazard_ratio_raw,
    metrics.relative_risk_raw,
    metrics.relative_risk_ratio_raw,
    metrics.incidence_rate_ratio_raw

FROM data_libraries.pgs_performance AS pp
LEFT JOIN data_libraries.evaluation_outcome_mappings AS eom
    ON eom.raw_outcome = pp.reported_trait
LEFT JOIN data_libraries.report_traits AS target_trait
    ON target_trait.report_trait_id = eom.target_report_trait_id
LEFT JOIN data_libraries.report_categories AS target_category
    ON target_category.category_id = target_trait.category_id
LEFT JOIN LATERAL (
    SELECT
        MAX(mv.estimate) FILTER (
            WHERE mv.metric_type = 'odds_ratio'
              AND mv.source = 'dedicated'
        ) AS odds_ratio_estimate,
        MAX(mv.ci_lower) FILTER (
            WHERE mv.metric_type = 'odds_ratio'
              AND mv.source = 'dedicated'
        ) AS odds_ratio_ci_lower,
        MAX(mv.ci_upper) FILTER (
            WHERE mv.metric_type = 'odds_ratio'
              AND mv.source = 'dedicated'
        ) AS odds_ratio_ci_upper,
        MAX(mv.effect_basis) FILTER (
            WHERE mv.metric_type = 'odds_ratio'
              AND mv.source = 'dedicated'
        ) AS odds_ratio_basis,
        COALESCE(
            BOOL_OR(mv.personalization_allowed) FILTER (
                WHERE mv.metric_type = 'odds_ratio'
                  AND mv.source = 'dedicated'
            ),
            FALSE
        ) AS odds_ratio_personalization_allowed,

        MAX(mv.estimate) FILTER (
            WHERE mv.metric_type = 'hazard_ratio'
              AND mv.source = 'dedicated'
        ) AS hazard_ratio_estimate,
        MAX(mv.ci_lower) FILTER (
            WHERE mv.metric_type = 'hazard_ratio'
              AND mv.source = 'dedicated'
        ) AS hazard_ratio_ci_lower,
        MAX(mv.ci_upper) FILTER (
            WHERE mv.metric_type = 'hazard_ratio'
              AND mv.source = 'dedicated'
        ) AS hazard_ratio_ci_upper,
        MAX(mv.effect_basis) FILTER (
            WHERE mv.metric_type = 'hazard_ratio'
              AND mv.source = 'dedicated'
        ) AS hazard_ratio_basis,
        COALESCE(
            BOOL_OR(mv.personalization_allowed) FILTER (
                WHERE mv.metric_type = 'hazard_ratio'
                  AND mv.source = 'dedicated'
            ),
            FALSE
        ) AS hazard_ratio_personalization_allowed,

        MAX(mv.estimate) FILTER (
            WHERE mv.metric_type = 'beta'
              AND mv.source = 'dedicated'
        ) AS beta_estimate,
        MAX(mv.ci_lower) FILTER (
            WHERE mv.metric_type = 'beta'
              AND mv.source = 'dedicated'
        ) AS beta_ci_lower,
        MAX(mv.ci_upper) FILTER (
            WHERE mv.metric_type = 'beta'
              AND mv.source = 'dedicated'
        ) AS beta_ci_upper,
        MAX(mv.effect_basis) FILTER (
            WHERE mv.metric_type = 'beta'
              AND mv.source = 'dedicated'
        ) AS beta_basis,

        MAX(mv.estimate) FILTER (
            WHERE mv.metric_type = 'auroc'
              AND mv.source = 'dedicated'
        ) AS auroc_estimate,
        MAX(mv.estimate) FILTER (
            WHERE mv.metric_type = 'c_index'
              AND mv.source = 'dedicated'
        ) AS c_index_estimate,

        MAX(mv.estimate) FILTER (WHERE mv.metric_type = 'r2') AS r2_value,
        MAX(mv.estimate) FILTER (WHERE mv.metric_type = 'incremental_r2') AS incremental_r2_value,
        MAX(mv.estimate) FILTER (WHERE mv.metric_type = 'partial_r2') AS partial_r2_value,
        MAX(mv.estimate) FILTER (WHERE mv.metric_type = 'pseudo_r2') AS pseudo_r2_value,
        MAX(mv.estimate) FILTER (WHERE mv.metric_type = 'adjusted_r2') AS adjusted_r2_value,
        MAX(mv.estimate) FILTER (WHERE mv.metric_type = 'liability_r2') AS liability_r2_value,

        STRING_AGG(DISTINCT mv.raw_metric, ' || ') FILTER (
            WHERE mv.metric_type = 'group_odds_ratio'
        ) AS group_odds_ratio_raw,
        STRING_AGG(DISTINCT mv.raw_metric, ' || ') FILTER (
            WHERE mv.metric_type = 'group_hazard_ratio'
        ) AS group_hazard_ratio_raw,
        STRING_AGG(DISTINCT mv.raw_metric, ' || ') FILTER (
            WHERE mv.metric_type = 'relative_risk'
        ) AS relative_risk_raw,
        STRING_AGG(DISTINCT mv.raw_metric, ' || ') FILTER (
            WHERE mv.metric_type = 'relative_risk_ratio'
        ) AS relative_risk_ratio_raw,
        STRING_AGG(DISTINCT mv.raw_metric, ' || ') FILTER (
            WHERE mv.metric_type = 'incidence_rate_ratio'
        ) AS incidence_rate_ratio_raw

    FROM data_libraries.pgs_performance_metric_values AS mv
    WHERE mv.ppm_id = pp.ppm_id
) AS metrics ON TRUE;

COMMIT;
