-- Initialize database with custom schema
-- This file will be executed when the PostgreSQL container starts

CREATE SCHEMA IF NOT EXISTS snpster_users;
CREATE SCHEMA IF NOT EXISTS data_libraries;

CREATE EXTENSION IF NOT EXISTS btree_gist;

ALTER DATABASE snpster_db SET search_path = snpster_users, public;

CREATE SEQUENCE IF NOT EXISTS snpster_users.imputation_jobs_seq START 1;
CREATE SEQUENCE IF NOT EXISTS snpster_users.prsc_jobs_seq START 1;
CREATE SEQUENCE IF NOT EXISTS snpster_users.report_jobs_seq START 1;

-- ===================================
-- User information table(s) to store user details
-- ===================================

CREATE TABLE snpster_users.user_information (
    user_id varchar(100) PRIMARY KEY NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE snpster_users.user_files (
    file_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id VARCHAR(100) NOT NULL
        REFERENCES snpster_users.user_information(user_id)
        ON DELETE CASCADE,

    genefile_location TEXT NOT NULL,

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE snpster_users.user_ancestry (
    user_id VARCHAR(100) PRIMARY KEY
        REFERENCES snpster_users.user_information(user_id)
        ON DELETE CASCADE,

    eur NUMERIC(8,6) CHECK (eur >= 0 AND eur <= 1),
    afr NUMERIC(8,6) CHECK (afr >= 0 AND afr <= 1),
    eas NUMERIC(8,6) CHECK (eas >= 0 AND eas <= 1),
    sas NUMERIC(8,6) CHECK (sas >= 0 AND sas <= 1),
    amr NUMERIC(8,6) CHECK (amr >= 0 AND amr <= 1),

    primary_ancestry VARCHAR(10)
        CHECK (primary_ancestry IN ('EUR', 'AFR', 'EAS', 'SAS', 'AMR')),

    primary_ancestry_percentage NUMERIC(8,6)
        CHECK (primary_ancestry_percentage >= 0 AND primary_ancestry_percentage <= 1),

    ancestry_method VARCHAR(100),
    reference_panel VARCHAR(100),

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

