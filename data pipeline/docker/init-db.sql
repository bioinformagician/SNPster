-- ===================================
-- Tables for handling everything from user uploaded data to imputation
-- ===================================

CREATE TABLE snpster_users.imputation_jobs (
    imputation_id integer PRIMARY KEY DEFAULT nextval('snpster_users.imputation_jobs_seq') NOT NULL,

    user_id varchar(100) NOT NULL
        REFERENCES snpster_users.user_information(user_id)
        ON DELETE CASCADE,

    imputation_status VARCHAR(20)
        CHECK (imputation_status IN ('queued', 'running', 'completed', 'failed')),

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ
);

CREATE TABLE snpster_users.imputation_job_parameters (
    imputation_id integer NOT NULL
        REFERENCES snpster_users.imputation_jobs(imputation_id)
        ON DELETE CASCADE,

    file_id BIGINT NOT NULL
        REFERENCES snpster_users.user_files(file_id)
        ON DELETE CASCADE,

    PRIMARY KEY (imputation_id, file_id)
);

CREATE TABLE snpster_users.imputed_data (
    imputation_id integer NOT NULL REFERENCES snpster_users.imputation_jobs(imputation_id) ON DELETE CASCADE,
    file_path TEXT,
    number_of_variants INTEGER,
    chromosome smallint CHECK (chromosome >= 1 AND chromosome <= 22),
    PRIMARY KEY (imputation_id, chromosome)
);

